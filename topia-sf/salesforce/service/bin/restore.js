/**
 * Contract section 9. A restore is a new plan through the same gate, generated by
 * the code from a saved pre-image. It targets only ids whose current value still
 * equals what was written, and lists the rest. A soft delete and a deploy have no
 * restore tool: they get a read, and guidance for a person.
 */
const TOOL = 'sf_restore_plan_execute';
const LISTED = 50;
function stop(reason, ctx, orgId = '') {
    if (ctx !== undefined) {
        try {
            appendJournal(ctx.projectRoot, { event: 'refusal', correlationId: ctx.correlationId, projectRoot: ctx.projectRoot, orgId, mode: ctx.mode, at: new Date(ctx.now).toISOString(), note: reason });
        }
        catch {
            // A refusal stands whether or not the journal could take it.
        }
    }
    return { ok: false, reason };
}
function reasonOf(result) {
    const message = result.data?.message;
    return result.notice ?? (typeof message === 'string' ? message : 'That could not be checked, so nothing was written.');
}
/** The journal isn't tamper-proof, and this isn't a claim that it is. It catches a file that's damaged or swapped by accident. */
function journaledHash(projectRoot, planId) {
    const lines = readJournal(projectRoot, planId).filter(line => line.event === 'preimage.saved' && typeof line.hash === 'string');
    return lines.at(-1)?.hash ?? null;
}
async function deleteGuidance(adapter, ctx, proven, source) {
    const seen = new Map();
    for (const part of chunked(source.frozenRecordIds, READ_CHUNK)) {
        const read = await adapter.query(proven.record.username, `SELECT Id, IsDeleted FROM ${source.object} WHERE Id IN (${part.map(id => `'${id}'`).join(', ')})`, { allRows: true });
        if (isFailure(read))
            return stop(`The Recycle Bin could not be checked. ${plainText(read.message, 200)}`);
        for (const row of read.records)
            seen.set(to18(String(row.Id)), row.IsDeleted === true);
    }
    const ids = source.frozenRecordIds;
    const inBin = ids.filter(id => seen.get(id) === true).length;
    const notDeleted = ids.filter(id => seen.get(id) === false).length;
    return resultOf(ctx, TOOL, proven, {
        planId: source.id,
        class: 'recycle-bin',
        inBin,
        notDeleted,
        purged: ids.length - inBin - notDeleted,
        guidance: `${REVERSIBILITY_TEXT['recycle-bin']} Topia has no tool for this. Tell the person the counts above, and that they can restore from the Recycle Bin in Setup. Restoring fires automation again. A lookup comes back only if it hasn't been replaced. If a record has gone from the bin, the saved pre-image can't bring back its id: inserting it again makes a new record.`,
        next: 'Nothing was written. This is a read, for a person to act on.',
    }, false);
}
function deployGuidance(ctx, proven, sourceId) {
    const hasSnapshot = existsSync(localFile(ctx.storeRoot, ctx.projectRoot, 'snapshots', sourceId).replace(/\.json$/, '.zip'));
    const data = {
        planId: sourceId,
        class: 'forward-only',
        cannotRestore: REDEPLOY_CANNOT_RESTORE,
        guidance: `${REVERSIBILITY_TEXT['forward-only']} What a redeploy can't restore: ${REDEPLOY_CANNOT_RESTORE.join(', ')}. Components the deploy added stay, because a snapshot only holds what was there before.`,
        snapshot: hasSnapshot,
        next: hasSnapshot ? `A redeploy is a new plan: deployment_plan with rollbackOf ${sourceId}, then its own validation and dialog. It voids other validations.` : 'No snapshot of the org from before this deploy is on this machine, so a redeploy has nothing to put back.',
    };
    return resultOf(ctx, TOOL, proven, data, false);
}
export async function prepareRestore(adapter, input, request, confirmedBriefHash, mode) {
    const ctx = { ...input, mode, stamp: null, brief: null };
    try {
        const lock = lockState(ctx.storeRoot, ctx.projectRoot);
        if (lock.state === 'off')
            return stop('Salesforce is not on for this project. /topia-sf:enable turns it on.');
        if (lock.state === 'unreadable')
            return stop(lock.message);
        if (!modeAllowsTool(mode, TOOL))
            return stop(`${TOOL} does not run in ${mode} mode. ${toolRefusal(TOOL, null) ?? ''}`.trim(), ctx);
        const brief = readBrief(ctx.storeRoot, ctx.projectRoot, request.briefId);
        if (brief === null || confirmedBriefHash === null || brief.briefHash !== confirmedBriefHash)
            return stop('A restore needs a brief a person has confirmed this session. Call sf_brief_confirm with its briefId first. A chat reply is not confirmation.', ctx);
        const loaded = loadPlan(ctx.storeRoot, ctx.projectRoot, request.planId, ctx.now, { allowExpired: true });
        if (!loaded.ok)
            return stop(loaded.reason);
        const live = await liveCheck(adapter, ctx, TOOL, loaded.plan.orgId);
        if ('ok' in live)
            return stop(reasonOf(live));
        const proven = live.ready;
        if (loaded.plan.kind === 'deploy')
            return deployGuidance(ctx, proven, loaded.plan.id);
        const source = loaded.plan;
        if (source.operation === 'delete')
            return deleteGuidance(adapter, ctx, proven, source);
        if (!effectiveLimits(proven.entry).allowedOperationClasses.includes('write'))
            return stop("This org's limits in orgs.json don't allow a write.");
        const ledger = readLedger(ctx.storeRoot, ctx.projectRoot, source.id);
        // An unanswered write may still land: a Bulk job for as long as it runs, and a Collections request for the settle window.
        const lastAttempt = ledger.state === 'unknown' && ledger.entry.kind === 'records' ? ledger.entry.attempts.at(-1) : undefined;
        const unanswered = lastAttempt !== undefined && lastAttempt.answered !== true && (lastAttempt.transport === 'bulk' || ctx.now - Date.parse(lastAttempt.startedAt) < SETTLE_MS);
        const running = ledger.state === 'started' || unanswered;
        if (running)
            return stop('That plan may still be running in the org, so a restore would race it. /topia-sf:verify reads it. It has to settle before anything is restored.', ctx, source.orgId);
        const image = readPreImage(ctx.storeRoot, ctx.projectRoot, source.id, ctx.now);
        if (image.state === 'missing')
            return stop('No pre-image of that plan is on this machine, so there is nothing to restore from.', ctx, source.orgId);
        if (image.state === 'unreadable')
            return stop(`The pre-image of that plan can not be read, so nothing can be restored from it: ${image.detail}.`, ctx, source.orgId);
        if (image.state === 'expired')
            return stop(`The pre-image of that plan expired at ${image.retainUntil}, after its 30 days, so nothing can be restored from it.`, ctx, source.orgId);
        const hash = journaledHash(ctx.projectRoot, source.id);
        if (hash === null || hash !== image.hash)
            return stop('The pre-image of that plan does not match the hash in the journal, so it is not trusted.', ctx, source.orgId);
        const { username } = proven.record;
        const fields = source.changedFields;
        const rows = await readRows(adapter, username, source.object, image.image.records.map(item => item.id), fields);
        if (isFailure(rows))
            return stop(`The records could not be read, so nothing can be restored. ${plainText(rows.message, 200)}`);
        const restorable = [];
        const conflicts = [];
        let alreadyOld = 0;
        const perRecord = {};
        const before = [];
        for (const item of image.image.records) {
            const row = rows.get(item.id);
            if (row === undefined) {
                conflicts.push(item.id);
                continue;
            }
            const written = intendedFor(loaded.values, item.id);
            const atOld = fields.every(field => sameValue(row[field], item.values[field], loaded.values.fieldTypes?.[field]));
            const atWritten = fields.every(field => sameValue(row[field], written[field], loaded.values.fieldTypes?.[field]));
            if (atOld)
                alreadyOld += 1;
            else if (atWritten) {
                restorable.push(item.id);
                perRecord[item.id] = Object.fromEntries(fields.map(field => [field, item.values[field] ?? null]));
                before.push({ id: item.id, systemModstamp: String(row.SystemModstamp) });
            }
            else
                conflicts.push(item.id);
        }
        if (restorable.length === 0) {
            return resultOf(ctx, TOOL, proven, { planId: source.id, counts: { total: image.image.records.length, restorable: 0, alreadyOld, conflicts: conflicts.length }, conflicts: conflicts.slice(0, LISTED), listedAtMost: LISTED, next: 'Nothing to restore, so nothing was written. Records with a conflict changed since, and they are not overwritten.' }, false);
        }
        const values = {
            user: username,
            businessObjective: `Restore plan ${source.id}.`,
            notes: '',
            fieldTypes: loaded.values.fieldTypes,
            perRecord,
            before,
            restoreOf: source.id,
            restoreConflicts: conflicts,
            restoreAlreadyOld: alreadyOld,
        };
        const plan = {
            version: 1,
            kind: 'records',
            id: `plan-${randomUUID()}`,
            orgId: proven.record.orgId,
            object: source.object,
            operation: 'update',
            changedFields: fields,
            frozenRecordIds: restorable,
            restoreOf: source.id,
            count: restorable.length,
            stateHash: sha256(canonical(before.map(item => ({ id: item.id, systemModstamp: item.systemModstamp })).sort((left, right) => left.id.localeCompare(right.id)))),
            valuesHash: sha256(canonical(values)),
            briefId: request.briefId,
            briefHash: brief.briefHash,
            briefConfirmed: true,
            // A code-generated plan has no review to point at. A review is a quality check on what a model proposed.
            practiceReviewId: 'generated-restore',
            reversibility: 'restorable',
            createdAt: new Date(ctx.now).toISOString(),
            expiresAt: expiryFrom(ctx.now),
        };
        const planHash = writePlan(ctx, plan, values);
        appendJournal(ctx.projectRoot, { event: 'change.proposed', correlationId: ctx.correlationId, planId: plan.id, projectRoot: ctx.projectRoot, orgId: plan.orgId, mode: ctx.mode, at: plan.createdAt, status: 'proposed', object: plan.object, counts: { rows: plan.count }, note: `A restore of ${source.id}, generated by the code. Plan hash ${planHash.slice(0, 12)}.` });
        return prepareRecordsWrite(adapter, input, { planId: plan.id }, confirmedBriefHash, mode, { tool: TOOL, restore: { conflicts: conflicts.length, sourcePlanId: source.id } });
    }
    catch (error) {
        return stop(error instanceof Error ? `The restore could not be prepared, so nothing was written. ${plainText(error.message, 300)}` : 'The restore could not be prepared, so nothing was written.');
    }
}
